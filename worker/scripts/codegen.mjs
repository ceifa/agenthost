// Browser scripts and the agent skill become plain-string modules, so wrangler,
// tsc and vitest need no loader rule.

import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { rolldown } from "rolldown";

const srcDir = new URL("../src/client/", import.meta.url);
const outDir = new URL("gen/", srcDir);
await mkdir(outDir, { recursive: true });

const entries = (await readdir(srcDir)).filter((f) => f.endsWith(".ts"));
for (const file of entries) {
  const bundle = await rolldown({
    input: fileURLToPath(new URL(file, srcDir)),
    platform: "browser",
    logLevel: "warn",
  });
  const { output } = await bundle.generate({ format: "iife", minify: true });
  await bundle.close();
  const code = output[0].code.trim();
  if (code.includes("</script")) throw new Error(`${file}: bundle contains "</script", which would break inlining`);
  const name = file.replace(/\.ts$/, "");
  const module = `// Generated by scripts/codegen.mjs from src/client/${file} — do not edit.\nexport default ${JSON.stringify(code)};\n`;
  await writeFile(new URL(`${name}.ts`, outDir), module);
  console.log(`client: ${file} → gen/${name}.ts (${code.length} bytes)`);
}

// The agent skill in ../skills/agenthost, served by the Worker under /skill/
// (see src/skill.ts). Written to src/gen/skill.ts as `{ "<path>": "<text>" }`.
const skillDir = fileURLToPath(new URL("../../skills/agenthost/", import.meta.url));
const skillFiles = {};
for (const entry of await readdir(skillDir, { recursive: true, withFileTypes: true })) {
  if (!entry.isFile()) continue;
  const path = join(entry.parentPath, entry.name);
  skillFiles[relative(skillDir, path).split(sep).join("/")] = await readFile(path, "utf8");
}
const genDir = new URL("../src/gen/", import.meta.url);
await mkdir(genDir, { recursive: true });
const skillModule = `// Generated by scripts/codegen.mjs from skills/agenthost — do not edit.\nconst files: Record<string, string> = ${JSON.stringify(skillFiles, null, 2)};\nexport default files;\n`;
await writeFile(new URL("skill.ts", genDir), skillModule);
console.log(`skill: ${Object.keys(skillFiles).join(", ")} → src/gen/skill.ts`);
