// Writes generated `export default "<string>"` modules into git-ignored gen/
// dirs, so the worker imports plain strings and neither wrangler, tsc nor vitest
// needs a loader rule.

import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { rolldown } from "rolldown";

async function emit(srcDir, source, name, text) {
  const outDir = new URL("gen/", srcDir);
  await mkdir(outDir, { recursive: true });
  const module = `// Generated by scripts/build-client.mjs from ${source} — do not edit.\nexport default ${JSON.stringify(text)};\n`;
  await writeFile(new URL(`${name}.ts`, outDir), module);
  console.log(`${source} → gen/${name}.ts (${text.length} bytes)`);
}

const clientDir = new URL("../src/client/", import.meta.url);
for (const file of (await readdir(clientDir)).filter((f) => f.endsWith(".ts"))) {
  const bundle = await rolldown({
    input: fileURLToPath(new URL(file, clientDir)),
    platform: "browser",
    logLevel: "warn",
  });
  const { output } = await bundle.generate({ format: "iife", minify: true });
  await bundle.close();
  const code = output[0].code.trim();
  if (code.includes("</script")) throw new Error(`${file}: bundle contains "</script", which would break inlining`);
  await emit(clientDir, `src/client/${file}`, file.replace(/\.ts$/, ""), code);
}

const skillDir = new URL("../src/skill/", import.meta.url);
for (const entry of await readdir(skillDir, { withFileTypes: true })) {
  if (!entry.isFile()) continue;
  const text = await readFile(new URL(entry.name, skillDir), "utf8");
  await emit(skillDir, `src/skill/${entry.name}`, entry.name.replace(/\.[^.]+$/, ""), text);
}
